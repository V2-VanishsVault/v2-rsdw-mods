"""Lists the game classes the API dump should cover, from the game's type map (.usmap), into
dev/framemage/data/api_classes.lua (developer only: not in releases).

    python tools/gen_api_classes.py [path/to/game.usmap]

Why: in game, UE4SS can't enumerate classes on this build (FindAllOf("Class") returns nothing), so the dump
looks each class up by name instead (from a live instance, or by its script path). The names come from here.
Keep PATTERNS in step with API_PATTERNS in framemage/features/inspector.lua.
"""
import glob
import os
import struct
import sys

PATTERNS = ["QuickAccess", "Inventory", "Loadout", "Equipment", "Spellcasting", "SpellBook", "Spellbook",
            "SpellData", "SpellPayload", "Radial", "ItemSlot", "ItemData", "ItemStack", "HeldEquipment", "Hotbar",
            "PlayerCharacter", "DomPlayerController", "ActionBar",
            "Crafting", "Recipe", "Station", "Pickup", "Pickupable", "Loot", "CarryWeight", "ItemWeight", "WeightBar"]
SKIP_PREFIXES = ("Default__", "SKEL_", "REINST_", "CUIS_", "GE_")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "dev", "framemage", "data", "api_classes.lua")  # developer only: not in releases
GAME = r"C:/Program Files (x86)/Steam/steamapps/common/RSDragonwilds/RSDragonwilds/Binaries/Win64/ue4ss"


def read_struct_names(path):
    """Names of every class / struct in an uncompressed, unversioned .usmap (v0-v4)."""
    d = open(path, "rb").read()
    _magic, ver = struct.unpack_from("<HB", d, 0)
    o = 3
    if ver >= 1:
        has_versioning, = struct.unpack_from("<i", d, o)
        o += 4
        if has_versioning:
            raise SystemExit("versioned .usmap not supported")
    comp = d[o]
    o += 1
    csize, _dsize = struct.unpack_from("<II", d, o)
    o += 8
    if comp != 0:
        raise SystemExit("compressed .usmap not supported")
    b = d[o:o + csize]
    pos = [0]

    def take(fmt):
        v = struct.unpack_from("<" + fmt, b, pos[0])
        pos[0] += struct.calcsize("<" + fmt)
        return v[0]

    names = []
    for _ in range(take("i")):
        n = take("H") if ver >= 2 else take("B")
        names.append(b[pos[0]:pos[0] + n].decode("utf-8", "replace"))
        pos[0] += n
    for _ in range(take("i")):  # enums
        take("i")
        cnt = take("H") if ver >= 3 else take("B")
        for _ in range(cnt):
            if ver >= 4:
                take("q")
            take("i")

    def ptype():
        t = take("B")
        if t == 26:              # Enum: inner type, enum name
            ptype()
            take("i")
        elif t == 9:             # Struct: struct name
            take("i")
        elif t in (8, 25, 28):   # Array, Set, Optional
            ptype()
        elif t == 24:            # Map
            ptype()
            ptype()

    out = []
    for _ in range(take("i")):
        out.append(names[take("i")])
        take("i")
        take("H")
        for _ in range(take("H")):
            take("H")
            take("B")
            take("i")
            ptype()
    return out


def wanted(name):
    if name.startswith(SKIP_PREFIXES):
        return False
    return any(p in name for p in PATTERNS)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else (glob.glob(os.path.join(GAME, "*.usmap")) or [None])[0]
    if not path:
        raise SystemExit("no .usmap found: pass its path")
    classes = sorted({n for n in read_struct_names(path) if wanted(n)})
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/gen_api_classes.py from the game's .usmap: the classes the API dump covers.\n")
        f.write("return {\n")
        for c in classes:
            f.write('    "%s",\n' % c)
        f.write("}\n")
    print("wrote %d classes to %s" % (len(classes), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
